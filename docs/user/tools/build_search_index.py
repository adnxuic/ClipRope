"""Rebuild the offline manual index after editing its HTML. Use --check in verification."""

import argparse
from html.parser import HTMLParser
import json
from pathlib import Path


MANUAL = Path(__file__).resolve().parents[1]
BLOCKS = {"p", "li", "dt", "dd", "th", "td", "caption", "figcaption"}


def join_text(parts):
    return " ".join("".join(parts).split())


class ManualPage(HTMLParser):
    def __init__(self):
        super().__init__()
        self.page_title = []
        self.description = ""
        self.heading = None
        self.anchor = None
        self.title = []
        self.body = []
        self.sections = []

    def handle_starttag(self, tag, attributes):
        attrs = dict(attributes)
        if tag == "meta" and attrs.get("name") == "description":
            self.description = attrs["content"]
        elif tag == "section" and "doc-section" in attrs.get("class", "").split():
            self.anchor = attrs["id"]
            self.title, self.body = [], []
        elif tag == "h1" or (tag == "h2" and self.anchor):
            self.heading = tag
        elif self.anchor and tag in BLOCKS:
            self.body.append(" ")

    def handle_data(self, data):
        if self.heading == "h1":
            self.page_title.append(data)
        elif self.heading == "h2":
            self.title.append(data)
        elif self.anchor:
            self.body.append(data)

    def handle_endtag(self, tag):
        if tag == self.heading:
            self.heading = None
        elif tag == "section" and self.anchor:
            self.sections.append((self.anchor, join_text(self.title), join_text(self.body)))
            self.anchor = None
        elif self.anchor and tag in BLOCKS:
            self.body.append(" ")


def render_index(page_dir):
    entries = []
    for source in sorted(page_dir.glob("*.html")):
        page = ManualPage()
        page.feed(source.read_text(encoding="utf-8"))
        page.close()
        page_name = join_text(page.page_title)
        entries.append(dict(page=page_name, title=page_name, url=source.name, body=page.description))
        for anchor, title, body in page.sections:
            entries.append(dict(page=page_name, title=title, url=f"{source.name}#{anchor}", body=body))
    data = json.dumps(entries, ensure_ascii=False, indent=2)
    return f"// Generated by tools/build_search_index.py from the manual pages.\nwindow.clipRopeSearchIndex = {data};\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report a stale index without writing it.")
    args = parser.parse_args()
    for page_dir, filename in [(MANUAL, "search-index.js"), (MANUAL / "en", "search-index.en.js")]:
        index = MANUAL / "js" / filename
        source = render_index(page_dir)
        if args.check:
            if not index.exists() or index.read_text(encoding="utf-8") != source:
                parser.exit(1, f"{filename} is stale. Run build_search_index.py.\n")
        else:
            index.write_text(source, encoding="utf-8")
